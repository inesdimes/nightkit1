_MASKS = {ch: np.array([[c == '#' for c in row] for row in rows], bool) for ch, rows in GLYPHS.items()}
ROWS = 8

def text_mask(text, scale=1):
    """boolean mask of a single line of text, 1 px gap (x scale) between glyphs"""
    cols = []
    for ch in text:
        g = _MASKS.get(ch, _MASKS['?']); cols.append(g); cols.append(np.zeros((ROWS, 1), bool))
    if not cols: return np.zeros((ROWS * scale, 1), bool)
    m = np.concatenate(cols[:-1], axis=1)
    return np.repeat(np.repeat(m, scale, axis=0), scale, axis=1) if scale > 1 else m

def text_width(text, scale=1): return text_mask(text, scale).shape[1]

def _dilate(m, r):
    out = m.copy()
    for dy in range(-r, r + 1):
        for dx in range(-r, r + 1):
            if dx == 0 and dy == 0: continue
            sh = np.zeros_like(m)
            ys = slice(max(0, dy), m.shape[0] + min(0, dy)); yd = slice(max(0, -dy), m.shape[0] + min(0, -dy))
            xs = slice(max(0, dx), m.shape[1] + min(0, dx)); xd = slice(max(0, -dx), m.shape[1] + min(0, -dx))
            sh[ys, xs] = m[yd, xd]; out |= sh
    return out

def draw_runs(img, x, y, runs, scale=1, outline=(34, 34, 42), outline_px=1, alpha=1.0):
    """draw one line made of coloured runs [(text, (r,g,b)), ...] on a numpy HxWx3 uint8 image at (x,y) = top-left of the glyph grid.
    The outline is the dilated union of all glyphs. Returns the bounding box (x0, y0, x1, y1)."""
    H, W = img.shape[:2]; pad = outline_px
    full = ''.join(t for t, _ in runs); mask_all = text_mask(full, scale)
    big = np.zeros((mask_all.shape[0] + 2 * pad, mask_all.shape[1] + 2 * pad), bool); big[pad:pad + mask_all.shape[0], pad:pad + mask_all.shape[1]] = mask_all
    ol = _dilate(big, pad) & ~big
    colour = np.zeros(big.shape + (3,), np.uint8); cx = pad
    for t, c in runs:                                              # colour each run on its own span of columns
        w = text_width(t, scale); sub = text_mask(t, scale)
        colour[pad:pad + sub.shape[0], cx:cx + w][sub] = c; cx += w + scale   # +scale = the gap glyph
    x0, y0 = int(x) - pad, int(y) - pad
    for layer, col, m in (('o', outline, ol), ('f', None, big)):
        ys, xs = np.nonzero(m); ys = ys + y0; xs = xs + x0; ok = (ys >= 0) & (ys < H) & (xs >= 0) & (xs < W)
        ys, xs = ys[ok], xs[ok]
        if len(ys) == 0: continue
        newc = np.array(outline, np.float32)[None, :] if col is not None else colour[(ys - y0), (xs - x0)].astype(np.float32)
        img[ys, xs] = (img[ys, xs].astype(np.float32) * (1 - alpha) + newc * alpha).astype(np.uint8)
    return (x0, y0, x0 + big.shape[1], y0 + big.shape[0])

def draw_text(img, x, y, text, fill=(242, 242, 234), scale=1, outline=(34, 34, 42), outline_px=1, alpha=1.0):
    return draw_runs(img, x, y, [(text, fill)], scale, outline, outline_px, alpha)

def wrap(words, max_w, scale=1):
    """words: [(word, colour)]. returns lines, each a list of (word, colour); a space glyph between words"""
    lines, cur, cw = [], [], 0; sp = text_width(' ', scale) + scale
    for w, c in words:
        ww = text_width(w, scale)
        if cur and cw + sp + ww > max_w: lines.append(cur); cur, cw = [], 0
        cw += (sp if cur else 0) + ww; cur.append((w, c))
    if cur: lines.append(cur)
    return lines

def line_runs(line):
    """merge a wrapped line back into runs, inserting the spaces (the space belongs to the previous run's colour = base fill)"""
    out = []
    for i, (w, c) in enumerate(line):
        if i: out.append((' ', line[i - 1][1]))
        out.append((w, c))
    return out
