FONT={k:[v[i*5:(i+1)*5] for i in range(7)] for k,v in _R.items()}
def check(s):
    miss=sorted(set(c for c in s.upper() if c not in FONT))
    if miss: raise ValueError(f"glyphs missing from font: {miss}")
def width(s,sc=1): return (len(s)*6-1)*sc
def text(d,s,x,y,col,sc=1,shadow=(0,0,0)):
    check(s)
    for k,ch in enumerate(s.upper()):
        for j,row in enumerate(FONT[ch]):
            for i,b in enumerate(row):
                if b=='1':
                    X=x+(k*6+i)*sc; Y=y+j*sc
                    if shadow: d.rectangle([X+sc,Y+sc,X+2*sc-1,Y+2*sc-1],fill=shadow)
                    d.rectangle([X,Y,X+sc-1,Y+sc-1],fill=col)
def ctext(d,s,y,col,W,sc=1,shadow=(0,0,0)): text(d,s,(W-width(s,sc))//2,y,col,sc,shadow)
